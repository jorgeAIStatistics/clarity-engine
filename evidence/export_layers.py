"""Export the shared evidence-layer rule table to the separately deployed frontend.
Usage: python3 -m evidence.export_layers ../clarity-web/src/platform/layers.generated.js
"""
import json
import sys
from pathlib import Path

SOURCE = Path(__file__).with_name('layers.json')


def render():
    rules = json.loads(SOURCE.read_text())
    return ('// Generated by clarity-engine `python3 -m evidence.export_layers`. Do not edit by hand.\n'
            f'export default {json.dumps(rules, indent=2, ensure_ascii=False)};\n')


if __name__ == '__main__':
    Path(sys.argv[1]).write_text(render())
